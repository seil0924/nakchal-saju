export const taekilBySlug = (s: string) => TAEKIL.find(t => t.slug === s) || null;

// 화면에서 쓰는 목록. 계산은 daypicker-en 하나로만 간다.
export function goodDays(slug: string, from: Date = new Date(), span = 90): DayPick[] {
  const t = taekilBySlug(slug);
  return t ? pickWith(t.good, from, span) : [];
}

export function badDays(from: Date = new Date(), span = 90): DayPick[] {
  return avoidDays(from, span);
}
