// ── 60갑자: 설립연도 → 년주 간지 + 오행 (기관마다 다른 명리 훅) ──
const GAN = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
const JI = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];
const GAN_H = ['甲', '乙', '丙', '丁', '戊', '己', '庚', '辛', '壬', '癸'];
const JI_H = ['子', '丑', '寅', '卯', '辰', '巳', '午', '未', '申', '酉', '戌', '亥'];
const GAN_OH = ['목', '목', '화', '화', '토', '토', '금', '금', '수', '수'];
const OH_TRAIT: Record<string, string> = {
  목: '뻗어 나가려는 성장·확장의 기운',
  화: '드러내고 확산하는 추진·홍보의 기운',
  토: '중심을 지키는 안정·신뢰의 기운',
  금: '원칙과 기준으로 가르는 결단·규격의 기운',
  수: '흐름을 읽고 적셔 가는 지혜·유연의 기운',
};

export function yearGanji(year: number) {
  const gi = ((year - 4) % 10 + 10) % 10;
  const ji = ((year - 4) % 12 + 12) % 12;
  return {
    gan: GAN[gi], ji: JI[ji], ganji: GAN[gi] + JI[ji],
    hanja: GAN_H[gi] + JI_H[ji], oh: GAN_OH[gi], trait: OH_TRAIT[GAN_OH[gi]],
  };
}

