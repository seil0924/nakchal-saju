import { describe, it, expect } from 'vitest';
import { holidaysOf, holidayOn } from '../holidays-kr';

// 2027년 월력요항 정리본(publog, 2026-10 확인)과 맞춘다. 노동절·제헌절이 처음 들어가는 해다.
describe('관공서 공휴일', () => {
  it('2027년: 대체공휴일까지 정리본과 같다', () => {
    const got = holidaysOf(2027).map(h => h.ymd);
    expect(got).toEqual([
      '2027-01-01',
      '2027-02-06', '2027-02-07', '2027-02-08', '2027-02-09',
      '2027-03-01',
      '2027-05-01', '2027-05-03', '2027-05-05', '2027-05-13',
      '2027-06-06',
      '2027-07-17', '2027-07-19',
      '2027-08-15', '2027-08-16',
      '2027-09-14', '2027-09-15', '2027-09-16',
      '2027-10-03', '2027-10-04', '2027-10-09', '2027-10-11',
      '2027-12-25', '2027-12-27',
    ]);
  });
  it('겹친 날은 대체공휴일이 하루뿐이다(2025년 어린이날·부처님오신날)', () => {
    const may = holidaysOf(2025).filter(h => h.ymd.startsWith('2025-05')).map(h => h.ymd);
    expect(may).toEqual(['2025-05-05', '2025-05-06']);
  });
  it('2026년 설: 2/16~18, 일요일이 없어 대체공휴일 없음', () => {
    const feb = holidaysOf(2026).filter(h => h.ymd.startsWith('2026-02')).map(h => h.ymd);
    expect(feb).toEqual(['2026-02-16', '2026-02-17', '2026-02-18']);
  });
  it('holidayOn 은 이름을 돌려준다', () => {
    expect(holidayOn('2027-02-09')?.name).toBe('설날 대체공휴일');
    expect(holidayOn('2027-02-10')).toBeNull();
  });
});
